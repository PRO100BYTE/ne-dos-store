const baseUrl = process.env.STORE_BASE_URL || 'http://localhost:8787';

async function request(url, options = {}) {
  const res = await fetch(`${baseUrl}${url}`, options);
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new Error(`${url} -> ${res.status} ${JSON.stringify(body)}`);
  }
  return body;
}

async function main() {
  const health = await request('/api/health');
  if (health.status !== 'ok') throw new Error('Health check failed');

  const authUser = `ci-user-${Date.now()}`;
  const initialPassword = 'CiPassword123';
  const updatedPassword = 'CiPassword456';
  const register = await request('/api/auth/passport/register', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      username: authUser,
      password: initialPassword,
      passwordConfirm: initialPassword,
      displayName: 'CI Uploader',
    }),
  });
  if (!register.session) throw new Error('Passport registration failed');

  const profileBefore = await request('/api/auth/profile', {
    headers: { 'x-nedos-session': register.session },
  });
  if (!profileBefore.account || profileBefore.account.username !== authUser) {
    throw new Error('Profile fetch after register failed');
  }

  const profileUpdated = await request('/api/auth/profile', {
    method: 'PATCH',
    headers: {
      'Content-Type': 'application/json',
      'x-nedos-session': register.session,
    },
    body: JSON.stringify({ displayName: 'CI Updated User' }),
  });
  if (profileUpdated.account?.displayName !== 'CI Updated User') {
    throw new Error('Profile update failed');
  }

  const passwordUpdated = await request('/api/auth/profile/password', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-nedos-session': profileUpdated.session,
    },
    body: JSON.stringify({ currentPassword: initialPassword, newPassword: updatedPassword }),
  });
  if (!passwordUpdated.session) {
    throw new Error('Password update failed');
  }

  const relogin = await request('/api/auth/passport/login', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: authUser, password: updatedPassword }),
  });
  if (!relogin.session) throw new Error('Passport login with new password failed');

  const adminLogin = await request('/api/auth/passport/login', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: process.env.PASSPORT_BOOTSTRAP_ADMIN || 'admin', password: process.env.PASSPORT_BOOTSTRAP_PASSWORD || 'admin123' }),
  });
  if (!adminLogin.session) throw new Error('Passport admin login failed');

  const meta = await request('/api/meta');
  if (!meta.count || meta.count < 70) throw new Error('Catalog count is unexpectedly low');

  const list = await request('/api/commands?query=weather');
  if (!list.items.some((item) => item.slug === 'weather')) throw new Error('Weather command missing');

  const install = await request('/api/commands/weather/install');
  if (!install.installSnippet || !install.sha256) throw new Error('Install payload missing sha256');

  const slug = `ci-cmd-${Date.now()}`;
  const submission = await request('/api/submissions', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'x-nedos-session': register.session },
    body: JSON.stringify({
      name: slug,
      title: 'CI Command',
      description: 'Generated by integration test',
      author: 'CI',
      category: 'community',
      tags: ['ci', 'test'],
      version: '0.0.1',
      scriptBody: `export default class ${slug.replace(/-/g, '_')} { description() { return 'CI'; } help(term) { term.writeln('help'); } execute(term) { term.writeln('ok'); } }`,
    }),
  });

  const approved = await request(`/api/admin/submissions/${submission.id}/approve`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-nedos-session': adminLogin.session,
    },
    body: JSON.stringify({ moderationNote: 'Approved in CI' }),
  });

  if (approved.status !== 'approved') throw new Error('Submission was not approved');

  const published = await request(`/api/commands/${slug}`);
  if (published.slug !== slug) throw new Error('Approved command not published');

  const packageRes = await fetch(`${baseUrl}/api/packages/submitted/${slug}.js`);
  if (!packageRes.ok) throw new Error('Approved package file missing');

  await request(`/api/commands/${slug}/reviews`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ authorName: 'CI Bot', rating: 5, comment: 'ok' }),
  });

  console.log('Integration checks passed.');
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
